export const GLYPH_W = 5;
export const GLYPH_H = 7;
const GAP = 1;

/* Pre-parse into arrays of booleans for a fast draw path. */
const BITS = new Map();
for (const [ch, spec] of Object.entries(FONT_SRC)) {
  const rows = spec.split(' ');
  BITS.set(ch, rows.map(r => r.split('').map(b => b === '1')));
}

function bitsFor(ch) {
  return BITS.get(ch) || BITS.get(ch.toUpperCase()) || BITS.get('?');
}

/** Pixel width of `text` at scale `s`. */
export function textWidth(text, s = 3) {
  return Math.max(0, String(text).length * (GLYPH_W + GAP) - GAP) * s;
}

/**
 * Draw `text` with the bitmap font.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x left edge in px
 * @param {number} y top edge in px
 * @param {number} s pixel scale
 * @param {string} color
 */
export function drawText(ctx, text, x, y, s = 3, color = '#ffffff') {
  ctx.fillStyle = color;
  const str = String(text);
  for (let i = 0; i < str.length; i++) {
    const rows = bitsFor(str[i]);
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      for (let c = 0; c < row.length; c++) {
        if (row[c]) ctx.fillRect(x + (i * (GLYPH_W + GAP) + c) * s, y + r * s, s, s);
      }
    }
  }
}

/** Render a standalone canvas of pixel text. */
export function pixelCanvas(text, color = '#ffffff', s = 3) {
  const cv = document.createElement('canvas');
  cv.width = Math.max(1, textWidth(text, s));
  cv.height = GLYPH_H * s;
  drawText(cv.getContext('2d'), text, 0, 0, s, color);
  return cv;
}
